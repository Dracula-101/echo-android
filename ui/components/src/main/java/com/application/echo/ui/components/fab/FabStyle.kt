/**
 * Visual treatment for [EchoFab] / [EchoExtendedFab].
 */
enum class FabStyle {
    /** Solid variant color — the default. */
    Filled,

    /** Tonal — variant container as background, on-container as content. */
    Tonal,

    /** Inverse surface — used over light/photo backgrounds. */
    Dark,
}
